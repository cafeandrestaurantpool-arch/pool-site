def build(tpl, OUT, BASE, URL, finalize, crumbs, prep_img):
    """ページを書き出し、(path, title) のリストを返す"""
    made = []
    for p in PAGES:
        d = os.path.join(OUT, p["slug"])
        os.makedirs(d, exist_ok=True)
        imgs = [(p["img"], p["alt"])] + p["gal"]
        sizes = {fn: prep_img(os.path.join(BASE, "img", fn), os.path.join(d, fn), 1600) for fn, _ in imgs}
        hero = f'<div class="hero2"><img src="/{p["slug"]}/{p["img"]}" alt="{e(p["alt"])}" width="{sizes[p["img"]][0]}" height="{sizes[p["img"]][1]}"></div>'
        gal = '<div class="gal">' + "".join(f'<img src="/{p["slug"]}/{fn}" alt="{e(a)}" width="{sizes[fn][0]}" height="{sizes[fn][1]}" loading="lazy">' for fn, a in p["gal"]) + "</div>"
        body = ""
        for i, (k, t) in enumerate(p["body"]):
            body += f'<h2 class="s2">{e(t)}</h2>' if k == "h2" else f"<p>{e(t)}</p>"
            if i == 2:
                body += gal
        faq = '<h2 class="s2">よくあるご質問</h2>' + "".join(f"<h3>{e(q)}</h3><p>{e(a)}</p>" for q, a in p["faq"])
        others = [x for x in PAGES if x["slug"] != p["slug"]]
        rel = '<p class="note">' + "　".join(f'<a href="/{x["slug"]}/">{e(x["h1"])} →</a>' for x in others) + f'　<a href="{WED}">貸切・ウエディング二次会 →</a></p>'
        cta = (f'<div class="go"><a class="f" href="{HP}" target="_blank" rel="noopener">ネット予約</a>'
               '<a href="tel:0742426430">電話 0742-42-6430</a>'
               '<a href="https://ig.me/m/cafeandrestaurant_pool" target="_blank" rel="noopener">InstagramのDM</a></div>')
        html_ = f'<p class="en">{p["en"]}</p><h1>{e(p["h1"])}</h1>{hero}{body}{cta}{faq}{ACCESS}{rel}'
        path = f'/{p["slug"]}/'
        faq_ld = {"@context": "https://schema.org", "@type": "FAQPage", "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in p["faq"]]}
        page_ld = {"@context": "https://schema.org", "@type": "WebPage", "name": p["title"], "url": URL + path, "inLanguage": "ja",
                   "about": {"@type": "Restaurant", "name": "CAFE & RESTAURANT POOL", "alternateName": "POOL（プール）", "url": URL + "/",
                             "telephone": "+81-742-42-6430", "address": {"@type": "PostalAddress", "postalCode": "630-8258", "addressRegion": "奈良県",
                                                                         "addressLocality": "奈良市", "streetAddress": "船橋町7", "addressCountry": "JP"}}}
        og = f'/og/{p["slug"]}.jpg'
        page = finalize(tpl.replace("{{BODY}}", html_), p["title"], p["desc"], path, og,
                        [page_ld, faq_ld, crumbs([("トップ", "/"), (p["h1"], path)])])
        open(os.path.join(d, "index.html"), "w", encoding="utf-8").write(page)
        made.append((path, p["img"]))
    return made
